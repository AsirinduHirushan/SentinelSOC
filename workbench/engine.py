"""SentinelSOC: offline, explainable alert-to-case triage engine.

Correlated items are *investigation candidates*, not proven attacks.
This module has no third-party dependencies and performs no network actions.
"""

from collections import Counter, defaultdict
from datetime import datetime, timezone
from hashlib import sha256
from pathlib import Path
import json

CATEGORY_RULES = {
    "60122": "Authentication",
    "100120": "Authentication",
    "550": "File Integrity",
    "100121": "Process Discovery",
    "92004": "Process Discovery",
    "92032": "Process Discovery",
}
CASE_WINDOW_SECONDS = 900  # 15-minute inactivity gap for investigation grouping


def normalize_alert(record):
    """Validate selected sanitized fields and return a normalized event."""
    if not isinstance(record, dict):
        raise ValueError("Expected JSON object")
    rid = str(record["rule_id"])
    level = record["level"]
    if not isinstance(level, int) or isinstance(level, bool) or not (0 <= level <= 15):
        raise ValueError("Level must be integer in 0..15")
    ts = datetime.fromisoformat(record["timestamp"])
    if ts.tzinfo is None:
        raise ValueError("Timestamp requires timezone")
    groups = record.get("groups", [])
    if not isinstance(groups, list) or any(not isinstance(g, str) for g in groups):
        raise ValueError("Groups must be list of strings")
    agent = str(record.get("agent", "unknown"))
    # Optional *already-pseudonymized* account token, not a plaintext username.
    actor = record.get("account_token")
    if actor is not None and (not isinstance(actor, str) or not actor.startswith("acct_")):
        raise ValueError("account_token must be an anonymized acct_ token")
    timestamp = ts.astimezone(timezone.utc)
    compact = {
        "timestamp": timestamp.isoformat(),
        "rule_id": rid,
        "level": level,
        "description": str(record.get("description", "Unspecified detection"))[:220],
        "agent": agent[:80],
        "groups": groups,
        "category": CATEGORY_RULES.get(rid, "Other"),
        "account_token": actor,
    }
    # Only accept correlation metadata generated by our trusted sanitizer.
    import re
    for field in ("process_token", "parent_process_token", "file_token", "source_event_token"):
        value = record.get(field)
        if value is not None:
            if not isinstance(value, str) or not re.fullmatch(r"[0-9a-f]{20}", value):
                raise ValueError(f"Invalid correlation token in {field}")
        compact[field] = value
    kind = record.get("source_kind")
    if kind not in (None, "Authentication", "Process", "File Integrity"):
        raise ValueError("Invalid source_kind")
    compact["source_kind"] = kind
    ref = record.get("event_ref")
    if ref is not None and (not isinstance(ref, str) or not re.fullmatch(r"[0-9a-f]{12}", ref)):
        raise ValueError("Invalid event_ref")
    compact["event_ref"] = ref
    safe_action = record.get("file_action")
    compact["file_action"] = safe_action if safe_action in ("added", "modified", "deleted") else None
    process = record.get("process_name")
    compact["process_name"] = process if process in ("cmd.exe", "powershell.exe", "pwsh.exe", "whoami.exe", "other") else None
    # Keep the legacy offline alert ID stable when extra metadata is added.
    legacy_keys = ("timestamp", "rule_id", "level", "description", "agent",
                   "groups", "category", "account_token")
    canonical = json.dumps({k: compact[k] for k in legacy_keys},
                           sort_keys=True, separators=(",", ":"))
    compact["alert_id"] = sha256(canonical.encode()).hexdigest()[:16]
    return compact


def load_jsonl(path):
    alerts, errors, seen = [], [], set()
    for lineno, raw in enumerate(Path(path).read_text(encoding="utf-8").splitlines(), 1):
        if not raw.strip():
            continue
        try:
            record = normalize_alert(json.loads(raw))
            if record["alert_id"] in seen:
                continue  # duplicate export row; not necessarily a duplicate source event
            seen.add(record["alert_id"])
            alerts.append(record)
        except (ValueError, TypeError, KeyError, json.JSONDecodeError) as exc:
            errors.append(f"Line {lineno}: {exc}")
    alerts.sort(key=lambda a: (a["timestamp"], a["alert_id"]))
    return alerts, errors


def risk_score(alerts):
    """Demonstration heuristic, not a validated probability of compromise."""
    top = max(a["level"] for a in alerts)
    factors = [("Highest Wazuh rule level", min(60, top * 4))]
    if len(alerts) > 1:
        factors.append(("Additional related alerts", min(20, (len(alerts) - 1) * 3)))
    if any(a["rule_id"] in ("100120", "100121") for a in alerts):
        factors.append(("Original custom detection", 10))
    if any(a["category"] == "Authentication" for a in alerts):
        times = [datetime.fromisoformat(a["timestamp"]) for a in alerts if a["rule_id"] == "60122"]
        # This counts timing patterns only; account identity may be missing.
        rapid = any((times[i + 2] - times[i]).total_seconds() <= 120 for i in range(len(times) - 2))
        if rapid:
            factors.append(("Three or more failures within 120 seconds (account not necessarily verified)", 10))
    return min(100, sum(v for _, v in factors)), factors


def group_cases(alerts, max_gap=CASE_WINDOW_SECONDS):
    """Group by agent/category and, only when available, pseudonymous actor.

    A missing token means we cannot establish that alerts relate to one account.
    """
    groups = defaultdict(list)
    for a in alerts:
        # Missing account token is explicitly not a same-account assertion.
        key = (a["agent"], a["category"], a["account_token"] if a["category"] == "Authentication" else None)
        groups[key].append(a)
    cases = []
    for (agent, category, token), events in groups.items():
        events.sort(key=lambda a: a["timestamp"])
        batch = []
        for e in events:
            if batch and (datetime.fromisoformat(e["timestamp"]) - datetime.fromisoformat(batch[-1]["timestamp"])).total_seconds() > max_gap:
                cases.append(make_case(agent, category, token, batch))
                batch = []
            batch.append(e)
        if batch:
            cases.append(make_case(agent, category, token, batch))
    return sorted(cases, key=lambda c: c["first_seen"], reverse=True)


def make_case(agent, category, token, alerts):
    first = alerts[0]["timestamp"]
    fingerprint = f"{agent}:{category}:{token or 'unknown'}:{alerts[0]['alert_id']}"
    cid = "CASE-" + sha256(fingerprint.encode()).hexdigest()[:8].upper()
    score, factors = risk_score(alerts)
    high_confidence_entity = category != "Authentication" or token is not None
    return {
        "case_id": cid,
        "agent": agent,
        "category": category,
        "account_token": token,
        "first_seen": first,
        "last_seen": alerts[-1]["timestamp"],
        "alert_count": len(alerts),
        "rule_counts": dict(sorted(Counter(a["rule_id"] for a in alerts).items())),
        "score": score,
        "score_factors": factors,
        "limitation": (
            "Account-level correlation is NOT verified: exported data has no account identifier. "
            "These are time-based investigation clusters, not confirmed incidents."
            if not high_confidence_entity else
            "This case is an investigation candidate, not proof of compromise."
        ),
        "alerts": alerts,
    }


def markdown_case_report(case, status="New", notes=""):
    def safe(value):
        return str(value).replace("|", "\\|").replace("\n", " ").replace("\r", " ")
    lines = [
        f"# SentinelSOC Investigation {case['case_id']}", "",
        f"- **Category:** {case['category']}",
        f"- **Endpoint:** {case['agent']}",
        f"- **Time (UTC):** {case['first_seen']} to {case['last_seen']}",
        f"- **Source alerts:** {case['alert_count']}",
        f"- **Triage score:** {case['score']}/100 (experimental heuristic, not likelihood of compromise)",
        f"- **Analyst status:** {safe(status)}", "",
        "## Why it was prioritized", "",
    ]
    lines += [f"- {safe(label)}: +{pts}" for label, pts in case["score_factors"]]
    lines += ["", "## Alert evidence", "", "| Time UTC | Rule | Level | Description |", "|---|---|---:|---|"]
    for a in case["alerts"]:
        lines.append(f"| {a['timestamp']} | {a['rule_id']} | {a['level']} | {safe(a['description'])} |")
    lines += ["", "## Analyst notes", "", notes.strip() or "Not yet reviewed.", "", "## Limitations", "", case["limitation"],
              "", "- Export contains a selected subset of Wazuh alerts, not all endpoint activity.",
              "- Multiple alerts can describe the same underlying process or action.",
              "- Timestamps and rule matches alone cannot prove an attack.", ""]
    return "\n".join(lines)
